"""Write report/generated/data.tex (macros + pgfplots coordinates) from the notebook's outputs.

Run from the project root after the notebook:  python report/make_report_data.py
Reads esahulat/outputs/ (current run, e5) and results/app_metrics.json (earlier stand-in run, kept for comparison).
"""
import ast
import glob
import json
import statistics
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "esahulat" / "outputs"
GEN = ROOT / "report" / "generated"
GEN.mkdir(parents=True, exist_ok=True)

load = lambda p: json.loads(Path(p).read_text(encoding="utf-8"), parse_constant=lambda _: None)
E5 = load(OUT / "app_metrics.json")
STUB = load(ROOT / "results" / "app_metrics.json")
PQ = pd.read_csv(OUT / "per_query_results.csv")
BLIND = pd.read_csv(sorted(glob.glob(str(OUT / "blind_results_*.csv")))[-1])
QUERIES = pd.read_csv(ROOT / "esahulat" / "data" / "queries_all.csv")
TEST = "TEST (previously inspected)"

lines = ["% generated by report/make_report_data.py; do not edit"]


def macro(name, value):
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def tex(s):
    return str(s).replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def pct(v, d=1):
    return "n/a" if v is None else f"{100 * v:.{d}f}\\%"


def coords(pairs):
    return " ".join(f"({x},{y})" for x, y in pairs)


# ---------------------------------------------------------------- configuration
macro("PipelineVersion", E5["version"])
macro("StubVersion", STUB["version"])
macro("DenseModel", tex(E5["dense_model"]))
macro("DenseBackend", E5["dense_backend"])
macro("FinalMethod", tex(E5["retriever"]))
macro("TauDense", E5["thresholds"]["dense"])
macro("TauCov", E5["thresholds"]["cov"])
macro("TauUnknown", E5["thresholds"]["unknown"])
macro("StubTauDense", STUB["thresholds"]["dense"])

# ---------------------------------------------------------------- data splits
by = QUERIES.groupby(["split", "language"]).size().unstack(fill_value=0)
blind_lang = BLIND.groupby("language").size()
splits = [("dev", "Dev"), ("test", "Test"), ("brief", "Brief")]
for lang, key in [("en", "En"), ("ur", "Ur"), ("roman_ur", "Roman")]:
    pts = [(label, int(by.loc[s, lang])) for s, label in splits] + [("Blind", int(blind_lang.get(lang, 0)))]
    lines.append(f"\\def\\Split{key}{{{coords(pts)}}}")
macro("NDev", int(by.loc["dev"].sum()))
macro("NTest", int(by.loc["test"].sum()))
macro("NBrief", int(by.loc["brief"].sum()))
macro("NBlind", len(BLIND))
macro("NQueriesAll", int(by.values.sum()) + len(BLIND))
dev_off = QUERIES[(QUERIES.split == "dev") & (QUERIES.source == "official")]
macro("NDevOfficial", len(dev_off))
macro("NDevTeam", int((QUERIES.split == "dev").sum()) - len(dev_off))

# ---------------------------------------------------------------- retrieval
methods = [r["method"] for r in E5["retrieval"]["dev"]]
lines.append("\\def\\RetMethods{" + ",".join(methods) + "}")
for split, key in [("dev", "Dev"), ("test", "Test")]:
    rows = {r["method"]: r for r in E5["retrieval"][split]}
    for metric, mkey in [("Recall@5", "Recall"), ("MRR@5", "MRR")]:
        lines.append(f"\\def\\Ret{key}{mkey}{{{coords((round(rows[m][metric], 3), m) for m in methods)}}}")
    macro(f"Ret{key}N", rows[methods[0]]["n"])
test_rows = {r["method"]: r for r in E5["retrieval"]["test"]}
macro("BaseRecall", f"{test_rows['BM25-raw']['Recall@5']:.3f}")
macro("BaseMRR", f"{test_rows['BM25-raw']['MRR@5']:.3f}")
macro("FinalRecall", f"{test_rows[E5['retriever']]['Recall@5']:.3f}")
macro("FinalMRR", f"{test_rows[E5['retriever']]['MRR@5']:.3f}")
macro("DenseRecall", f"{test_rows['Dense']['Recall@5']:.3f}")
macro("HybridLexMRR", f"{test_rows['Hybrid+lex']['MRR@5']:.3f}")

# ---------------------------------------------------------------- blind: baseline vs stand-in vs e5
blind_metrics = [("decision accuracy", "Decision acc."), ("answer recall (answerable answered)", "Answer recall"),
                 ("false-answer rate on unanswerable", "False answers"), ("CITATION SUPPORT (verifier pass and gold)", "Citation support"),
                 ("retrieval Recall@5", "Recall@5"), ("retrieval MRR@5", "MRR@5")]
lines.append("\\def\\BlindLabels{" + ",".join(l for _, l in blind_metrics) + "}")
for src, key in [(E5["blind_baseline"], "Base"), (STUB["blind"], "Stub"), (E5["blind"], "Efive")]:
    lines.append(f"\\def\\Blind{key}{{{coords((l, round(src[k], 3)) for k, l in blind_metrics)}}}")
for k, name in [("decision accuracy", "Acc"), ("false-answer rate on unanswerable", "False"), ("answer recall (answerable answered)", "Recall"),
                ("CITATION SUPPORT (verifier pass and gold)", "Cite"), ("retrieval Recall@5", "RecallFive"), ("retrieval MRR@5", "MRR"),
                ("cross-language: all variants correct", "Cross")]:
    macro(f"BlindBase{name}", pct(E5["blind_baseline"][k]))
    macro(f"BlindStub{name}", pct(STUB["blind"][k]))
    macro(f"BlindEfive{name}", pct(E5["blind"][k]))
    macro(f"BlindN{name}", E5["blind_n"].get(k, ""))

# blind accuracy by language
acc_lang = BLIND.groupby("language")["correct"].mean()
lines.append(f"\\def\\BlindLang{{{coords((l, round(acc_lang.get(c, 0), 3)) for c, l in [('en', 'English'), ('ur', 'Urdu'), ('roman_ur', 'Roman Urdu')])}}}")


def blind_error(r):
    if r.correct and (r.got != "answer" or not r.expected_decision == "answer" or r.cited_is_gold or pd.isna(r.gold_evidence_ids)):
        return None
    if r.expected_decision != "answer" and r.got == "answer":
        return "False answer"
    if r.expected_decision == "answer" and r.got != "answer":
        return "Missed answer"
    if r.expected_decision == "answer" and r.got == "answer" and not r.cited_is_gold:
        return "Wrong passage"
    if not r.correct:
        return "Clarify/abstain mix-up"
    return None


errs = BLIND.apply(blind_error, axis=1).dropna().value_counts()
order = ["Wrong passage", "False answer", "Missed answer", "Clarify/abstain mix-up"]
lines.append("\\def\\BlindErrLabels{" + ",".join(order) + "}")
lines.append(f"\\def\\BlindErr{{{coords((int(errs.get(o, 0)), o) for o in order)}}}")

# ---------------------------------------------------------------- decisions by split
dm = [("decision accuracy", "Decision acc."), ("answer recall (answerable answered)", "Answer recall"),
      ("false-answer rate on unanswerable", "False answers")]
lines.append("\\def\\DecLabels{" + ",".join(l for _, l in dm) + "}")
for split, key in [(TEST, "Test"), ("BRIEF", "Brief"), ("DEV", "Dev")]:
    lines.append(f"\\def\\Dec{key}{{{coords((l, round(E5['decisions'][split][k] or 0, 3)) for k, l in dm)}}}")
    macro(f"Dec{key}N", int(E5["decisions"][split]["n"]))
td = E5["decisions"][TEST]
macro("TestAcc", pct(td["decision accuracy"]))
macro("TestFalse", pct(td["false-answer rate on unanswerable"]))
macro("TestAnsRec", pct(td["answer recall (answerable answered)"]))
macro("TestCite", pct(E5["citations"][TEST]["CITATION SUPPORT RATE"]))
macro("DevAcc", pct(E5["decisions"]["DEV"]["decision accuracy"]))
macro("DevFalse", pct(E5["decisions"]["DEV"]["false-answer rate on unanswerable"]))
macro("StubDevFalse", pct(STUB["decisions"]["DEV"]["false-answer rate on unanswerable"]))
macro("StubTestAcc", pct(STUB["decisions"][TEST]["decision accuracy"]))

# ---------------------------------------------------------------- confusion matrix as tikz nodes
cm = E5["confusion_test"]
inner = [v for row in cm["values"][:-1] for v in row[:-1]]
vmax = max(inner)
cells = []
for i, r in enumerate(cm["rows"]):
    for j, c in enumerate(cm["cols"]):
        v = cm["values"][i][j]
        total = r == "All" or c == "All"
        shade = 0 if total else int(round(15 + 70 * v / vmax)) if v else 0
        ink = "white" if shade > 55 else "black"
        fill = "black!4" if total else f"esgreen!{shade}" if v else "white"
        cells.append(f"\\node[cmcell,fill={fill},text={ink}] at ({j},{-i}) {{{v}}};")
lines.append("\\def\\ConfCells{" + "".join(cells) + "}")
lines.append("\\def\\ConfRows{" + ",".join(f"{i}/{tex(r)}" for i, r in enumerate(cm["rows"])) + "}")
lines.append("\\def\\ConfCols{" + ",".join(f"{j}/{tex(c)}" for j, c in enumerate(cm["cols"])) + "}")

# ---------------------------------------------------------------- latency
lat_e5, lat_stub = E5["latency_test_ms"], STUB["latency_test_ms"]
q = lambda xs, p: float(np.percentile(xs, p))
macro("LatEfivePfifty", f"{q(lat_e5, 50):.1f}")
macro("LatEfivePninetyfive", f"{q(lat_e5, 95):.1f}")
macro("LatStubPfifty", f"{q(lat_stub, 50):.1f}")
macro("LatStubPninetyfive", f"{q(lat_stub, 95):.1f}")
counts, edges = np.histogram(lat_e5, bins=np.arange(50, 155, 7.5))
lines.append(f"\\def\\LatHist{{{coords((round((a + b) / 2, 2), int(c)) for a, b, c in zip(edges[:-1], edges[1:], counts))}}}")
lines.append(f"\\def\\LatBars{{(Stand-in p50,{q(lat_stub, 50):.1f}) (Stand-in p95,{q(lat_stub, 95):.1f}) (e5 p50,{q(lat_e5, 50):.1f}) (e5 p95,{q(lat_e5, 95):.1f})}}")

# ---------------------------------------------------------------- threshold: dev dense score by expected decision
dev = PQ[PQ.split == "dev"].reset_index(drop=True)
rng = np.random.default_rng(42)
for exp, key, y in [("answer", "Ans", 1), ("abstain", "Abs", 0), ("clarify", "Cla", 0)]:
    sub = dev[dev.expected == exp]
    pts = [(round(d, 4), round(y + rng.uniform(-0.22, 0.22), 3)) for d in sub.dense]
    lines.append(f"\\def\\Thr{key}{{{coords(pts)}}}")
    macro(f"ThrN{key}", len(sub))
ans_below = int(((dev.expected == "answer") & (dev.dense < E5["thresholds"]["dense"])).sum())
neg_above = int(((dev.expected != "answer") & (dev.dense >= E5["thresholds"]["dense"])).sum())
macro("ThrAnsBelow", ans_below)
macro("ThrNegAbove", neg_above)

# ---------------------------------------------------------------- cross-script and recall by language
cs = E5["cross_script"]
macro("CrossTopOne", pct(cs["dev: same top-1 in en/ur/roman"]))
macro("CrossAllHit", pct(cs["dev: all 3 scripts hit@5"]))
macro("CrossSV", pct(cs["test SV(noisy roman) top-1 = dev EN top-1"]))
macro("CrossJaccard", f"{cs['dev: mean pairwise Jaccard@5']:.3f}")

# ---------------------------------------------------------------- test errors
err = pd.read_csv(OUT / "error_analysis.csv")
for split, key in [("test", "Test"), ("brief", "Brief")]:
    e = err[err.split == split]
    macro(f"{key}Errors", len(e))
    macro(f"{key}ErrSibling", int((e.error_type == "wrong passage: confusable sibling").sum()))
    macro(f"{key}ErrMissed", int(e.error_type.str.startswith("missed answer").sum()))
    macro(f"{key}ErrUnrelated", int((e.error_type == "wrong passage: unrelated").sum()))

(GEN / "data.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {GEN / 'data.tex'} ({len(lines)} lines)")
